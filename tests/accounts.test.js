import { describe, it, before, after } from 'node:test';
import assert from 'node:assert/strict';
import { api, resetDatabase, closeDatabase, createAccount, NON_EXISTENT_ID } from './helpers.js';

const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;

before(resetDatabase);
after(closeDatabase);

describe('POST /api/accounts', () => {
  it('creates an account with a generated id, balance 0 and server timestamp', async () => {
    const before = Date.now();
    const res = await api().post('/api/accounts').send({ name: '  Alice  ' });

    assert.equal(res.status, 201);
    assert.equal(res.body.success, true);
    const account = res.body.data;
    assert.match(account.id, UUID_RE);
    assert.equal(account.name, 'Alice', 'name is trimmed');
    assert.equal(account.balance, 0);
    assert.ok(Date.parse(account.created_at) >= before - 5000, 'created_at is generated by the server');
    assert.equal(res.headers.location, `/api/accounts/${account.id}`);
  });

  it('generates unique ids', async () => {
    const a = await createAccount('A');
    const b = await createAccount('B');
    assert.notEqual(a.id, b.id);
  });

  it('rejects a missing name', async () => {
    const res = await api().post('/api/accounts').send({});
    assert.equal(res.status, 400);
    assert.equal(res.body.error.code, 'VALIDATION_ERROR');
    assert.equal(res.body.error.message, 'name is required');
  });

  it('rejects a blank name', async () => {
    const res = await api().post('/api/accounts').send({ name: '   ' });
    assert.equal(res.status, 400);
    assert.equal(res.body.error.message, 'name must not be empty');
  });

  it('rejects a non-string name', async () => {
    const res = await api().post('/api/accounts').send({ name: 123 });
    assert.equal(res.status, 400);
    assert.equal(res.body.error.message, 'name must be a string');
  });

  it('does not allow the client to set the initial balance', async () => {
    const res = await api().post('/api/accounts').send({ name: 'Rich', balance: 1000 });
    assert.equal(res.status, 400);
    assert.equal(res.body.error.details[0].field, 'balance');
    assert.match(res.body.error.message, /set by the server/);
  });

  it('does not allow the client to set id or created_at', async () => {
    const res = await api()
      .post('/api/accounts')
      .send({ name: 'X', id: NON_EXISTENT_ID, created_at: '2020-01-01' });
    assert.equal(res.status, 400);
    assert.deepEqual(res.body.error.details.map((d) => d.field).sort(), ['created_at', 'id']);
  });

  it('returns INVALID_JSON for a malformed body', async () => {
    const res = await api().post('/api/accounts').set('Content-Type', 'application/json').send('{"name":');
    assert.equal(res.status, 400);
    assert.equal(res.body.error.code, 'INVALID_JSON');
  });

  it('rejects a request without a JSON body', async () => {
    const res = await api().post('/api/accounts');
    assert.equal(res.status, 400);
    assert.equal(res.body.error.code, 'VALIDATION_ERROR');
  });

  it('rejects a JSON body that is not an object', async () => {
    const res = await api().post('/api/accounts').send(['Alice']);
    assert.equal(res.status, 400);
    assert.equal(res.body.error.message, 'Request body must be a JSON object');
  });
});

describe('GET /api/accounts/:id and /balance', () => {
  it('returns the account details', async () => {
    const account = await createAccount('Bob');
    const res = await api().get(`/api/accounts/${account.id}`);
    assert.equal(res.status, 200);
    assert.deepEqual(res.body.data, account);
  });

  it('returns account_id and balance', async () => {
    const account = await createAccount('Carol');
    const res = await api().get(`/api/accounts/${account.id}/balance`);
    assert.equal(res.status, 200);
    assert.deepEqual(res.body, { success: true, data: { account_id: account.id, balance: 0 } });
  });

  it('returns 404 ACCOUNT_NOT_FOUND for an unknown account', async () => {
    const res = await api().get(`/api/accounts/${NON_EXISTENT_ID}/balance`);
    assert.equal(res.status, 404);
    assert.equal(res.body.error.code, 'ACCOUNT_NOT_FOUND');
    assert.equal(res.body.error.details.account_id, NON_EXISTENT_ID);
  });

  it('returns 400 INVALID_ACCOUNT_ID for a malformed id', async () => {
    const res = await api().get('/api/accounts/not-a-uuid/balance');
    assert.equal(res.status, 400);
    assert.equal(res.body.error.code, 'INVALID_ACCOUNT_ID');
  });
});

describe('General', () => {
  it('returns 404 ROUTE_NOT_FOUND for unknown routes', async () => {
    const res = await api().get('/api/nope');
    assert.equal(res.status, 404);
    assert.equal(res.body.error.code, 'ROUTE_NOT_FOUND');
  });

  it('health check reports database connectivity', async () => {
    const res = await api().get('/health');
    assert.equal(res.status, 200);
    assert.equal(res.body.data.database, 'connected');
  });
});
